#!/usr/bin/env ruby
# Offline extraction of factual VGA timing records; never opens USB devices.
require 'digest'
path = ARGV.fetch(0) { abort "usage: #{$PROGRAM_NAME} blob-rodata.bin" }
data = File.binread(path)
expected = '31ff54b0c379bf3e1b13389e7792cf87e0f53b47a72b24566f40b24bbde2e751'
abort 'unexpected vendor .rodata SHA256' unless Digest::SHA256.hexdigest(data) == expected
rows = 137.times.filter_map do |index|
  row = data.byteslice(0x1a3fc0 + index * 24, 24).unpack('Vv8V')
  refresh, width, _hf, _hs, _hb, height, _vf, _vs, _vb, flags = row
  next unless (flags & 3) == 3 && (flags & 0x20).zero?
  next unless width <= 1024 && height <= 768 && (40_000..120_000).cover?(refresh)
  [index, row]
end
puts <<~HEADER
  /* Generated by tools/extract_modes.rb from original vendor object SHA256
   * 536b9be25b310d57a77d2888fe83cd2e499417dbb963129edc90357cf9736dbb.
   * VESA_get_vesamodes_table (.text+0x255d0): .rodata+0x1a3fc0,
   * 137 little-endian 24-byte records. Table order determines score ties.
   * Progressive valid rows, at most 1024x768 and 40..120 Hz; polarity
   * flags 0x40/0x80 are retained. Hardware validation is separate.
   * Regenerate: ruby tools/extract_modes.rb blob-rodata.bin > src/vesa_modes.h
   */
  #ifndef V2U_VESA_MODES_H
  #define V2U_VESA_MODES_H
  struct v2u_vesa_timing {
      unsigned refresh, width, hfront, hsync, hback, height, vfront, vsync, vback, flags;
  };
  static const struct v2u_vesa_timing v2u_vesa_modes[] = {
HEADER
rows.each do |index, row|
  values = row[0...-1].join(', ') + ", 0x#{row.last.to_s(16)}"
  puts "    {#{values}}, /* vendor row #{index} */"
end
puts "};\n#endif"
